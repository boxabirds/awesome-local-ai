import { z } from 'zod';
import { TASK_DESCRIPTION_MAX, TASK_NAME_MAX, WORKSPACE_NAME_MAX } from './limits';

/** Public shape of a workspace. Never includes the secret or its hash. */
export const Workspace = z.object({
  id: z.string(),
  name: z.string(),
  version: z.number().int(),
  createdAt: z.string(),
});
export type Workspace = z.infer<typeof Workspace>;

/** The stored row fields the public shape is built from. */
export type WorkspaceRowLike = {
  id: string;
  name: string;
  version: number;
  created_at: string;
};

/** Maps a stored row to the public shape. Picks fields explicitly so secret_hash can never leak. */
export function toPublicWorkspace(row: WorkspaceRowLike): Workspace {
  return { id: row.id, name: row.name, version: row.version, createdAt: row.created_at };
}

