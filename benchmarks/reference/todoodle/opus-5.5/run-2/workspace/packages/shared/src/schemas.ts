/* Tasks (story 5). */

/** A task id: 16 random bytes as lowercase hex, generated by the client (idempotent create). */
export const TaskIdSchema = z.string().regex(/^[0-9a-f]{32}$/);

/** Public shape of a task. Stories 7 and 8 add nullable projectId and dueDate. */
export const TaskSchema = z.object({
  id: TaskIdSchema,
  workspaceId: z.string(),
  name: z.string(),
  description: z.string(),
  sortOrder: z.number(),
  completedAt: z.string().nullable(),
  version: z.number().int(),
  createdAt: z.string(),
  updatedAt: z.string(),
});
export type Task = z.infer<typeof TaskSchema>;

/**
 * Length check in UTF-16 code units (String.length), the same measure the client's counters use.
 * zod's .max() counts code points, which would let an emoji-heavy text past the client's limit.
 */
const fitsIn = (max: number) => (value: string) => value.length <= max;

/**
 * Body of POST /api/w/:id/tasks. Unknown keys are stripped (story 7 adds projectId). Lengths are
 * String.length (UTF-16 code units) after trimming. The server is the final length guard.
 */
export const CreateTaskInputSchema = z.object({
  id: TaskIdSchema,
  name: z.string().trim().min(1).refine(fitsIn(TASK_NAME_MAX), { message: `At most ${TASK_NAME_MAX} characters` }),
  description: z
    .string()
    .trim()
    .refine(fitsIn(TASK_DESCRIPTION_MAX), { message: `At most ${TASK_DESCRIPTION_MAX} characters` })
    .optional()
    .default(''),
});
export type CreateTaskInput = z.infer<typeof CreateTaskInputSchema>;

export const TaskResponse = z.object({ task: TaskSchema });
export type TaskResponse = z.infer<typeof TaskResponse>;

/** Query of GET /api/w/:id/tasks. `list` defaults to inbox; stories 7 and 8 add values. */
export const TaskListQuerySchema = z.object({ list: z.enum(['inbox']).default('inbox') });
export type TaskListQuery = z.infer<typeof TaskListQuerySchema>;
export type TaskList = TaskListQuery['list'];

export const TaskListResponse = z.object({ tasks: z.array(TaskSchema) });
export type TaskListResponse = z.infer<typeof TaskListResponse>;

/** GET /api/w/:id/counts: open tasks per list. Stories 7 and 8 add fields. */
export const CountsSchema = z.object({ inbox: z.number().int().nonnegative() });
export type Counts = z.infer<typeof CountsSchema>;
