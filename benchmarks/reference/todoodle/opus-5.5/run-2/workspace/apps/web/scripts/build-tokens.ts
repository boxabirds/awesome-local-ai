// Generates src/styles/tokens.css from packages/shared/src/tokens.ts and src/styles/constants.css
// from packages/shared/src/limits.ts (run: `bun run tokens`; the Vite build regenerates both).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MIN_TOUCH_TARGET_PX, MOBILE_BREAKPOINT_PX } from '../../../packages/shared/src/limits';
import { PROJECT_COLOR_TOKENS, THEME_TOKENS, type Theme } from '../../../packages/shared/src/tokens';

function vars(theme: Theme, indent: string): string {
  const lines = Object.entries(THEME_TOKENS[theme]).map(([name, value]) => `${indent}--${name}: ${value};`);
  for (const [name, value] of Object.entries(PROJECT_COLOR_TOKENS[theme])) lines.push(`${indent}--project-${name}: ${value};`);
  return lines.join('\n');
}

export function renderTokensCss(): string {
  return `/* Generated by apps/web/scripts/build-tokens.ts from packages/shared/src/tokens.ts. Do not edit. */

:root {
  color-scheme: light dark;
${vars('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars('dark', '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation: none !important;
    transition: none !important;
  }
}
`;
}

/** Layout constants as CSS custom properties, so CSS never hard-codes 768 or 44. */
export function renderConstantsCss(): string {
  return `/* Generated by apps/web/scripts/build-tokens.ts from packages/shared/src/limits.ts. Do not edit. */

:root {
  --mobile-breakpoint: ${MOBILE_BREAKPOINT_PX}px;
  --min-touch-target: ${MIN_TOUCH_TARGET_PX}px;
}
`;
}

export const GENERATED_CSS: Array<{ path: string; render: () => string }> = [
  { path: fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url)), render: renderTokensCss },
  { path: fileURLToPath(new URL('../src/styles/constants.css', import.meta.url)), render: renderConstantsCss },
];

/** Writes every generated stylesheet whose content changed; returns the paths written. */
export function writeGeneratedCss(): string[] {
  const written: string[] = [];
  for (const { path, render } of GENERATED_CSS) {
    const css = render();
    let current: string | null = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // Not generated yet.
    }
    if (current === css) continue;
    writeFileSync(path, css);
    written.push(path);
  }
  return written;
}

if (import.meta.main) {
  for (const path of writeGeneratedCss()) console.log(`wrote ${path}`);
}
