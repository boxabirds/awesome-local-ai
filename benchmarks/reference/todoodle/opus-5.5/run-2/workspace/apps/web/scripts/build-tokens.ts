// Generates src/styles/tokens.css from packages/shared/src/tokens.ts (run: `bun run tokens`).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PROJECT_COLOR_TOKENS, THEME_TOKENS, type Theme } from '../../../packages/shared/src/tokens';

function vars(theme: Theme, indent: string): string {
  const lines = Object.entries(THEME_TOKENS[theme]).map(([name, value]) => `${indent}--${name}: ${value};`);
  for (const [name, value] of Object.entries(PROJECT_COLOR_TOKENS[theme])) lines.push(`${indent}--project-${name}: ${value};`);
  return lines.join('\n');
}

export function renderTokensCss(): string {
  return `/* Generated by apps/web/scripts/build-tokens.ts from packages/shared/src/tokens.ts. Do not edit. */

:root {
  color-scheme: light dark;
${vars('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars('dark', '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation: none !important;
    transition: none !important;
  }
}
`;
}

if (import.meta.main) {
  const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
  writeFileSync(out, renderTokensCss());
  console.log(`wrote ${out}`);
}
