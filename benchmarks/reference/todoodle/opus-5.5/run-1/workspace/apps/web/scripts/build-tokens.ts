// Generates src/styles/tokens.css from packages/shared/src/tokens.ts, and src/styles/constants.css from
// packages/shared/src/limits.ts (story 5), so CSS never hard-codes a shared number. Run with `bun run tokens`.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  MIN_TOUCH_TARGET_PX,
  MOBILE_BREAKPOINT_PX,
  QUICK_ADD_MAX_DESCRIPTION_ROWS,
  TASK_ROW_INTRINSIC_HEIGHT_PX,
} from '../../../packages/shared/src/limits.ts';
import {
  PROJECT_COLORS,
  PROJECT_COLOR_TOKENS,
  SEMANTIC_TOKENS,
  TOKENS,
  type Theme,
  projectColorVar,
} from '../../../packages/shared/src/tokens.ts';

export function renderTokensCss(): string {
  const vars = (theme: Theme, indent: string) =>
    [
      ...SEMANTIC_TOKENS.map((token) => `${indent}--${token}: ${TOKENS[theme][token]};`),
      ...PROJECT_COLORS.map((color) => `${indent}${projectColorVar(color)}: ${PROJECT_COLOR_TOKENS[theme][color]};`),
    ].join('\n');

  return `/* GENERATED by apps/web/scripts/build-tokens.ts from packages/shared/src/tokens.ts. Do not edit. */

:root {
  color-scheme: light dark;
${vars('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars('dark', '    ')}
  }
}

/* The edit-gate fieldset (className="contents") must not affect layout. */
fieldset {
  min-width: 0;
  border: 0;
  margin: 0;
  padding: 0;
}

@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation: none !important;
    transition: none !important;
  }
}
`;
}

/** Shared layout numbers as CSS custom properties (media queries can't read them: those use Tailwind `md`). */
export function renderConstantsCss(): string {
  return `/* GENERATED by apps/web/scripts/build-tokens.ts from packages/shared/src/limits.ts. Do not edit. */

:root {
  --mobile-breakpoint: ${MOBILE_BREAKPOINT_PX}px;
  --min-touch-target: ${MIN_TOUCH_TARGET_PX}px;
  --task-row-intrinsic-height: ${TASK_ROW_INTRINSIC_HEIGHT_PX}px;
  --quick-add-max-description-rows: ${QUICK_ADD_MAX_DESCRIPTION_ROWS};
}
`;
}

if (import.meta.main) {
  for (const [file, css] of [
    ['tokens.css', renderTokensCss()],
    ['constants.css', renderConstantsCss()],
  ] as const) {
    const out = path.join(import.meta.dirname, '../src/styles', file);
    writeFileSync(out, css);
    console.log(`Wrote ${path.relative(process.cwd(), out)}`);
  }
}
