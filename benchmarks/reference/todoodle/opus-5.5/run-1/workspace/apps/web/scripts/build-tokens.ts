// Generates src/styles/tokens.css from packages/shared/src/tokens.ts. Run with `bun run tokens`.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  PROJECT_COLORS,
  PROJECT_COLOR_TOKENS,
  SEMANTIC_TOKENS,
  TOKENS,
  type Theme,
  projectColorVar,
} from '../../../packages/shared/src/tokens.ts';

export function renderTokensCss(): string {
  const vars = (theme: Theme, indent: string) =>
    [
      ...SEMANTIC_TOKENS.map((token) => `${indent}--${token}: ${TOKENS[theme][token]};`),
      ...PROJECT_COLORS.map((color) => `${indent}${projectColorVar(color)}: ${PROJECT_COLOR_TOKENS[theme][color]};`),
    ].join('\n');

  return `/* GENERATED by apps/web/scripts/build-tokens.ts from packages/shared/src/tokens.ts. Do not edit. */

:root {
  color-scheme: light dark;
${vars('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars('dark', '    ')}
  }
}

/* The edit-gate fieldset (className="contents") must not affect layout. */
fieldset {
  min-width: 0;
  border: 0;
  margin: 0;
  padding: 0;
}

@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation: none !important;
    transition: none !important;
  }
}
`;
}

if (import.meta.main) {
  const out = path.join(import.meta.dirname, '../src/styles/tokens.css');
  writeFileSync(out, renderTokensCss());
  console.log(`Wrote ${path.relative(process.cwd(), out)}`);
}
