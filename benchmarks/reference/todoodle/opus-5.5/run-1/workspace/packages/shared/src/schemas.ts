// ---------------------------------------------------------------- story 5: tasks

/** A task id: TASK_ID_BYTES random bytes as lowercase hex. Generated by the client, so a create is idempotent. */
export const TaskIdSchema = z.string().regex(new RegExp(`^[0-9a-f]{${TASK_ID_BYTES * 2}}$`));

/** A project id (story 7): PROJECT_ID_BYTES random bytes as lowercase hex, generated by the client like task ids. */
export const ProjectIdSchema = z.string().regex(new RegExp(`^[0-9a-f]{${PROJECT_ID_BYTES * 2}}$`));

/**
 * Length check in UTF-16 code units (String.length), the unit the client's counters use. zod's own .max()
 * counts code points, which would let an emoji-heavy name past the limit the user was shown.
 */
function fitsUnits(limit: number) {
  return (value: string) => value.length <= limit;
}

/** Public shape of a task. Story 7 adds projectId (null = Inbox) and story 8 dueDate (both nullable). */
export const TaskSchema = z.object({
  id: TaskIdSchema,
  workspaceId: z.string(),
  /** The task's project; null (or absent in pre-story-7 payloads) means the Inbox. */
  projectId: z.string().nullable().default(null),
  name: z.string(),
  description: z.string(),
  sortOrder: z.number(),
  completedAt: z.string().nullable(),
  version: z.number().int(),
  createdAt: z.string(),
  updatedAt: z.string(),
  /** Story 8: the due date (a calendar date); null (or absent in pre-story-8 payloads) means no date. */
  dueDate: localDateSchema.nullable().default(null),
});
export type Task = z.infer<typeof TaskSchema>;

/**
 * POST /api/w/:id/tasks. Lengths are String.length (UTF-16 code units) after trimming. Unknown keys are
 * stripped. projectId (story 7): a missing or null projectId means the Inbox.
 */
export const CreateTaskInputSchema = z.object({
  id: TaskIdSchema,
  name: z.string().trim().min(1).refine(fitsUnits(TASK_NAME_MAX), { message: `At most ${TASK_NAME_MAX} characters` }),
  description: z
    .string()
    .trim()
    .refine(fitsUnits(TASK_DESCRIPTION_MAX), { message: `At most ${TASK_DESCRIPTION_MAX} characters` })
    .default(''),
  projectId: ProjectIdSchema.nullable().optional(),
  /** Story 8: a missing or null dueDate means no date. */
  dueDate: localDateSchema.nullable().optional(),
});
export type CreateTaskInput = z.infer<typeof CreateTaskInputSchema>;

/**
 * GET /api/w/:id/tasks?list=. Story 7 widens it to a union on `list`: the Inbox (the default), or one
 * project, which requires projectId. Story 8 adds 'today'.
 */
export const TaskListQuerySchema = z.union([
  z.object({ list: z.literal('project'), projectId: ProjectIdSchema }),
  z.object({ list: z.literal('inbox').default('inbox') }),
]);
export type TaskListQuery = z.infer<typeof TaskListQuerySchema>;
export type TaskList = TaskListQuery['list'];

/** Per-project task counts: open = not completed; total = open + completed (exactly what a project delete removes). */
export const ProjectCountsSchema = z.object({ open: z.number().int().nonnegative(), total: z.number().int().nonnegative() });
export type ProjectCounts = z.infer<typeof ProjectCountsSchema>;

/**
 * GET /api/w/:id/counts. inbox = open tasks with no project. Story 7 adds `projects` (every active project,
 * zeros included; deleted projects absent). Story 8 adds fields.
 */
export const CountsSchema = z.object({
  inbox: z.number().int().nonnegative(),
  projects: z.record(z.string(), ProjectCountsSchema).default({}),
  /**
   * Story 8: open tasks due on or before the viewer's date (Today + Overdue), excluding deleted projects. Only
   * when the request carried ?date= (never computed from the server clock).
   */
  today: z.number().int().nonnegative().optional(),
});
/** `projects` is optional in the type (pre-story-7 payloads and fixtures); the API always sends it. */
export type Counts = z.input<typeof CountsSchema>;

export const TaskResponse = z.object({ task: TaskSchema });
export type TaskResponse = z.infer<typeof TaskResponse>;

export const TaskListResponse = z.object({ tasks: z.array(TaskSchema) });
export type TaskListResponse = z.infer<typeof TaskListResponse>;

// ---------------------------------------------------------------- story 6: edit, completed lists

/**
 * A task edit (PATCH /api/w/:id/tasks/:taskId). Lifecycle fields (completedAt, deleted…) can't be patched.
 * projectId (story 7) moves the task: null = Inbox.
 */
export type TaskPatch = { name?: string; description?: string; projectId?: string | null; dueDate?: LocalDate | null };

/**
 * PATCH body: strict (unknown keys are 400, so completion can't be tampered with through PATCH), at least one
 * field. Both are trimmed and measured in UTF-16 code units. A blank name is valid here and means "keep the
 * previous name" (resolvePatchedName); an empty description clears it. Story 8: dueDate (null clears).
 */
export const TaskPatchSchema: z.ZodType<TaskPatch> = z
  .object({
    name: z.string().trim().refine(fitsUnits(TASK_NAME_MAX), { message: `At most ${TASK_NAME_MAX} characters` }).optional(),
    description: z
      .string()
      .trim()
      .refine(fitsUnits(TASK_DESCRIPTION_MAX), { message: `At most ${TASK_DESCRIPTION_MAX} characters` })
      .optional(),
    projectId: ProjectIdSchema.nullable().optional(),
    /** Story 8: sets the due date; null clears it. */
    dueDate: localDateSchema.nullable().optional(),
  })
  .strict()
  .refine((patch) => patch.name !== undefined || patch.description !== undefined || patch.projectId !== undefined || patch.dueDate !== undefined, {
    message: 'Change at least one field',
  });

/** The name a patch leaves: the trimmed input, or `previous` when the input is absent or blank (prd.edit_blank_name). */
export function resolvePatchedName(input: string | undefined, previous: string): string {
  if (input === undefined) return previous;
  const trimmed = input.trim();
  return trimmed === '' ? previous : trimmed;
}

/**
 * GET /api/w/:id/tasks query: story 5's list plus include_completed (only the literal strings true/false).
 * Story 7: list=project requires a well-formed projectId; the Inbox ignores projectId.
 */
export const ListTasksQuerySchema = z
  .object({
    list: z.enum(['inbox', 'project']).default('inbox'),
    projectId: ProjectIdSchema.optional(),
    include_completed: z.enum(['true', 'false']).optional(),
  })
  .refine((query) => query.list !== 'project' || query.projectId !== undefined, {
    message: 'list=project needs a projectId',
    path: ['projectId'],
  });
export type ListTasksQuery = z.infer<typeof ListTasksQuerySchema>;

const IncludeCompletedSchema = z.enum(['true', 'false']).optional();

/** include_completed: absent or 'false' -> false, 'true' -> true; any other value throws (a 400 on the API). */
export function parseIncludeCompleted(value: string | undefined): boolean {
  return IncludeCompletedSchema.parse(value) === 'true';
}

/** Bodyless lifecycle calls (complete, reopen, restore) accept no body or exactly `{}`. */
export const EmptyBodySchema = z.object({}).strict();

type Orderable = { id: string; sortOrder: number; completedAt: string | null };

/** Compares ids byte-wise (not locale-aware), so the order is identical on the server and in every browser. */
function compareIds(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * The one task order (tasks.list_completed): open tasks by sortOrder ascending, then completed tasks by
 * completedAt descending (most recent first); ties by id. Returns a new array.
 */
export function orderTasks<T extends Orderable>(tasks: readonly T[]): T[] {
  return tasks.toSorted((a, b) => {
    const aDone = a.completedAt !== null;
    const bDone = b.completedAt !== null;
    if (aDone !== bDone) return aDone ? 1 : -1;
    if (aDone && bDone && a.completedAt !== b.completedAt) return a.completedAt! < b.completedAt! ? 1 : -1;
    if (!aDone && a.sortOrder !== b.sortOrder) return a.sortOrder - b.sortOrder;
    return compareIds(a.id, b.id);
  });
}

