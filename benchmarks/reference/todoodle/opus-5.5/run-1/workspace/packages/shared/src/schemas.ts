/**
 * Story 8: a calendar date 'YYYY-MM-DD' (no time, no zone) within DUE_DATE_MIN_YEAR..DUE_DATE_MAX_YEAR. Every
 * date-relative request carries the viewer's own local date in this form; the server only validates it.
 */
export const localDateSchema: z.ZodType<LocalDate> = z.string().refine(isCalendarDate, { message: 'Not a calendar date (YYYY-MM-DD)' });

/** Public shape of a workspace. Never includes the secret or its hash. */
export const Workspace = z.object({
  id: z.string(),
  name: z.string(),
  version: z.number().int(),
  createdAt: z.string(),
});
export type Workspace = z.infer<typeof Workspace>;

/** The persisted columns `toPublicWorkspace` reads (a subset of the D1 row). */
export type WorkspaceRecord = {
  id: string;
  name: string;
  version: number;
  created_at: string;
};

/** Maps a stored row to the public shape. Only whitelisted fields are copied, so secret_hash can never leak. */
export function toPublicWorkspace(row: WorkspaceRecord): Workspace {
  return { id: row.id, name: row.name, version: row.version, createdAt: row.created_at };
}

