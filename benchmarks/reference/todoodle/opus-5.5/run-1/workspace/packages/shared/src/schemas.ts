// ---------------------------------------------------------------- story 5: tasks

/** A task id: TASK_ID_BYTES random bytes as lowercase hex. Generated by the client, so a create is idempotent. */
export const TaskIdSchema = z.string().regex(new RegExp(`^[0-9a-f]{${TASK_ID_BYTES * 2}}$`));

/**
 * Length check in UTF-16 code units (String.length), the unit the client's counters use. zod's own .max()
 * counts code points, which would let an emoji-heavy name past the limit the user was shown.
 */
function fitsUnits(limit: number) {
  return (value: string) => value.length <= limit;
}

/** Public shape of a task. Story 7 adds projectId and story 8 dueDate (both nullable). */
export const TaskSchema = z.object({
  id: TaskIdSchema,
  workspaceId: z.string(),
  name: z.string(),
  description: z.string(),
  sortOrder: z.number(),
  completedAt: z.string().nullable(),
  version: z.number().int(),
  createdAt: z.string(),
  updatedAt: z.string(),
});
export type Task = z.infer<typeof TaskSchema>;

/**
 * POST /api/w/:id/tasks. Lengths are String.length (UTF-16 code units) after trimming. Unknown keys are
 * stripped (story 7 adds projectId; a missing projectId always means Inbox).
 */
export const CreateTaskInputSchema = z.object({
  id: TaskIdSchema,
  name: z.string().trim().min(1).refine(fitsUnits(TASK_NAME_MAX), { message: `At most ${TASK_NAME_MAX} characters` }),
  description: z
    .string()
    .trim()
    .refine(fitsUnits(TASK_DESCRIPTION_MAX), { message: `At most ${TASK_DESCRIPTION_MAX} characters` })
    .default(''),
});
export type CreateTaskInput = z.infer<typeof CreateTaskInputSchema>;

