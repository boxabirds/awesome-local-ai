// Story 3 e2e helpers: people on one board, and the waiting that live
// collaboration needs.
//
// Each person is their own browser context, which is what "two people" means to
// a browser test: separate sockets, separate documents, no storage and no
// BroadcastChannel shared between them, so the only way a change can get from
// one screen to the other is through the board's room.
//
// Waiting is `expectEventually`: a change is expected to arrive, and it is
// waited for up to E2E_EVENTUAL_TIMEOUT_MS. How long it took is measured and
// printed against LIVE_UPDATE_LATENCY_BUDGET_MS and never asserted — the model,
// the browsers and the server all share this one machine, so wall-clock timing
// here is not a pass/fail signal (design: Timing policy).
import { expect, type Browser, type BrowserContext, type Page } from '@playwright/test';
import { newBoardId } from '../../../src/shared/board-id';
import {
  CATCH_UP_TEST_OUTAGE_MS,
  E2E_EVENTUAL_TIMEOUT_MS,
  LIVE_UPDATE_LATENCY_BUDGET_MS,
} from '../../../src/shared/config';
import { boardPath } from '../../../src/shared/routes';
import { UNREACHABLE_SERVER } from '../../../src/client/sync/emulateOutage';

/** One person: a browser context of their own, and the page they are looking at. */
export interface Person {
  name: string;
  context: BrowserContext;
  page: Page;
  /** Anything the page said that it should not have: console errors and exceptions. */
  problems: string[];
  /**
   * This person is meant to be unable to reach the board right now, so what
   * their socket says about it is the outage happening rather than something
   * wrong. `loseTheBoard` sets it; `expectBoardAgreedAgain` clears it, which is
   * the moment the board is reachable again and complaints start counting.
   */
  expectingOutage: boolean;
}

/** Everything about the notes as one page draws them, comparable between pages. */
export interface BoardState {
  count: number;
  /** One line per note, in the order they are drawn: id, x, y, colour, text. */
  notes: string[];
}

export const line = (id: string, x: string, y: string, color: string, text: string): string =>
  `${id}|${x}|${y}|${color}|${text}`;

/**
 * A board nobody has been on yet. The address is generated by the same function
 * the app uses, so a test opens a board exactly the way a person does.
 */
export function newBoard(): string {
  return newBoardId();
}

/**
 * A socket refused at the address an emulated outage sends its retries to is the
 * outage happening, not something going wrong. Everything else the page complains
 * about is a problem.
 */
function isEmulatedOutage(text: string): boolean {
  return text.includes(UNREACHABLE_SERVER);
}

/** A person joins a board, and is not considered present until their side of
 *  the board has been agreed with the room. */
export async function joinBoard(browser: Browser, name: string, boardId: string): Promise<Person> {
  const context = await browser.newContext();
  const page = await context.newPage();
  const person: Person = { name, context, page, problems: [], expectingOutage: false };
  // What the page complains about is collected as it happens, because a
  // complaint that went by in a moment is not recoverable afterwards.
  const isOutage = (text: string): boolean =>
    person.expectingOutage && /websocket/i.test(text);
  page.on('console', (message) => {
    if (message.type() !== 'error') return;
    if (isEmulatedOutage(message.text()) || isOutage(message.text())) return;
    person.problems.push(`${name}: console.error — ${message.text()}`);
  });
  page.on('pageerror', (error) => {
    if (isEmulatedOutage(String(error)) || isOutage(String(error))) return;
    person.problems.push(`${name}: uncaught error — ${String(error)}`);
  });
  page.on('requestfailed', (request) => {
    // A socket that fails to connect is the thing under test in the outage
    // cases; nothing else is expected to fail.
    if (isEmulatedOutage(request.url()) || isOutage(request.url())) return;
    if (!request.url().includes('/api/rooms/')) {
      person.problems.push(`${name}: request failed — ${request.url()} ${request.failure()?.errorText ?? ''}`);
    }
  });

  await page.goto(boardPath(boardId));
  await waitForBoard(page);
  return person;
}

/**
 * The board is open and agreed: the test hook is installed, the start point is
 * centred (as `gotoBoard` waits for in stories 1 and 2), and the room has
 * agreed this document — which is the point at which a change made anywhere on
 * the board will be seen here.
 */
export async function waitForBoard(page: Page): Promise<void> {
  await expect
    .poll(
      async () =>
        page.evaluate(() => {
          const hook = window.__vidi6;
          if (hook === undefined) return 'no-hook';
          const camera = hook.getCamera();
          const centred =
            Math.abs(camera.x + window.innerWidth / 2) < 1 &&
            Math.abs(camera.y + window.innerHeight / 2) < 1;
          return centred ? hook.connectionState() : 'centring';
        }),
      { timeout: E2E_EVENTUAL_TIMEOUT_MS },
    )
    .toBe('connected');
}

/** What this page's connection says, right now. */
export function connectionStateOf(page: Page): Promise<string> {
  return page.evaluate(() => window.__vidi6?.connectionState() ?? 'missing-hook');
}

/** The badge as a person sees it, or null when there is nothing to show. */
export async function badgeOf(page: Page): Promise<string | null> {
  const badge = page.locator('[data-testid="connection-status"]');
  if ((await badge.count()) === 0) return null;
  return (await badge.textContent())?.trim() ?? null;
}

export async function expectBadge(page: Page, text: string, label: string): Promise<void> {
  await expectEventually(label, () => badgeOf(page), text);
}

export async function expectNoBadge(page: Page, label: string): Promise<void> {
  await expectEventually(label, () => badgeOf(page), null);
}

/**
 * Watch everything the badge says and everything the connection reports, for as
 * long as the page is open. Both come and go — "Connected" is up for two seconds
 * and a reconnection may last less than a polling interval — so a test that has
 * to know what happened in an interval of time cannot get it from asking at
 * moments; it has to have been listening.
 */
export async function watchConnection(page: Page): Promise<void> {
  await page.evaluate(() => {
    const w = window as unknown as {
      __badge: string[];
      __states: string[];
    };
    w.__badge = [];
    w.__states = [];
    const readBadge = (): string | null => {
      const el = document.querySelector('[data-testid="connection-status"]');
      return el === null ? null : (el.textContent ?? '').trim();
    };
    const record = (): void => {
      const badge = readBadge();
      if (badge !== null && w.__badge[w.__badge.length - 1] !== badge) w.__badge.push(badge);
      const state = window.__vidi6?.connectionState();
      if (state !== undefined && w.__states[w.__states.length - 1] !== state) w.__states.push(state);
    };
    new MutationObserver(record).observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });
    // The state is not in the DOM when the badge is hidden, so it is sampled too.
    setInterval(record, 200);
    record();
  });
}

export function badgesSeen(page: Page): Promise<string[]> {
  return page.evaluate(() => (window as never as { __badge: string[] }).__badge);
}

export function statesSeen(page: Page): Promise<string[]> {
  return page.evaluate(() => (window as never as { __states: string[] }).__states);
}

/**
 * Watch every state of every note this page draws, and remember every moment
 * each one was seen. A test that made a change elsewhere asks this page when it
 * saw that exact state, which is the change arriving on this screen — the thing
 * the latency budget is about.
 *
 * States are remembered in a list rather than one per note because a note can
 * come back to a state it was in before (yellow, then pink, then yellow again):
 * the question "when did this change arrive" has to be answered about the change
 * that just happened, not about the first time this page ever drew that colour.
 */
export async function watchNotes(page: Page): Promise<void> {
  await page.evaluate(() => {
    const w = window as unknown as {
      __seen: Record<string, { key: string; at: number }[]>;
      /** When did this page last draw this note in this state, at or after `notBefore`? -1 if never. */
      __sawAfter(id: string, key: string, notBefore: number): number;
      /** Every state this page drew this note in, oldest first, for a failure message. */
      __statesOf(id: string): string[];
    };
    w.__seen = {};
    const keyOf = (el: Element): string => {
      const style = (el as HTMLElement).style;
      const text = el.querySelector('.sticky-text');
      return [
        el.getAttribute('data-note-id'),
        style.left,
        style.top,
        getComputedStyle(el).backgroundColor,
        text?.textContent ?? '',
      ].join('|');
    };
    const record = (): void => {
      const at = Date.now();
      const present = new Set<string>();
      for (const el of Array.from(document.querySelectorAll('[data-note-id]'))) {
        const id = el.getAttribute('data-note-id')!;
        present.add(id);
        const key = keyOf(el);
        const seen = (w.__seen[id] ??= []);
        if (seen[seen.length - 1]?.key !== key) seen.push({ key, at });
      }
      // A note that is no longer drawn is a state of its own, and the one a
      // deletion has to be measured against.
      for (const id of Object.keys(w.__seen)) {
        const seen = w.__seen[id]!;
        if (!present.has(id) && seen[seen.length - 1]?.key !== 'gone') seen.push({ key: 'gone', at });
      }
    };
    const world = document.querySelector('[data-testid="world-layer"]') ?? document.body;
    new MutationObserver(record).observe(world, {
      attributes: true,
      attributeFilter: ['style', 'class'],
      subtree: true,
      childList: true,
      characterData: true,
    });
    record();
    w.__sawAfter = (id: string, key: string, notBefore: number): number => {
      record();
      for (const entry of w.__seen[id] ?? []) {
        if (entry.key === key && entry.at >= notBefore) return entry.at;
      }
      return -1;
    };
    w.__statesOf = (id: string): string[] => (w.__seen[id] ?? []).map((entry) => entry.key);
  });
}

/** The clock a page and this process have in common: `Date.now()` in both. */
const CLOCK_SLACK_MS = 100;

/**
 * Wait until this page has drawn a note in the state the sender is in, and
 * report how long that took. `sentAt` is the moment the change was made on the
 * sender's screen, so the number is the whole of what the budget covers: that
 * screen to this one. A state the page was already in before then does not
 * count: only what it drew from that moment on is this change arriving.
 */
export async function expectChangeSeen(
  who: Person,
  noteId: string,
  state: string,
  sentAt: number,
  label: string,
): Promise<void> {
  const asked = { id: noteId, key: state, notBefore: sentAt - CLOCK_SLACK_MS };
  const saw = (): Promise<number> =>
    who.page.evaluate(
      (asked: { id: string; key: string; notBefore: number }) =>
        (window as never as { __sawAfter(id: string, key: string, notBefore: number): number }).__sawAfter(
          asked.id,
          asked.key,
          asked.notBefore,
        ),
      asked,
    );
  try {
    await expect
      .poll(async () => (await saw()) !== -1, { timeout: E2E_EVENTUAL_TIMEOUT_MS, intervals: [50, 100, 250] })
      .toBe(true);
  } catch {
    // What this page did draw is the difference between a change that never
    // arrived and one that arrived as something else, so it is said here rather
    // than left to a screenshot.
    const states = await who.page.evaluate(
      (id: string) => (window as never as { __statesOf(id: string): string[] }).__statesOf(id),
      noteId,
    );
    throw new Error(
      `${label}: ${who.name} never drew note ${noteId} as [${state}]\n` +
        states.map((drawn, index) => `  ${index + 1}. [${drawn}]`).join('\n'),
    );
  }
  // The moment this page first drew that note in that state, which is this
  // change arriving on this screen.
  const at = await saw();
  record(label, who.name, at - sentAt);
}

/** The notes as this page draws them, in the order they are drawn. */
export function boardStateOf(page: Page): Promise<BoardState> {
  return page.evaluate(() => {
    const notes = Array.from(document.querySelectorAll('[data-note-id]')).map((el) => {
      const style = (el as HTMLElement).style;
      const text = el.querySelector('.sticky-text');
      return [
        el.getAttribute('data-note-id'),
        style.left,
        style.top,
        getComputedStyle(el).backgroundColor,
        text?.textContent ?? '',
      ].join('|');
    });
    return { count: notes.length, notes };
  });
}

/** One note's state as this page draws it, in the same form `watchNotes` records. */
export function noteKeyOf(page: Page, id: string): Promise<string> {
  return page.evaluate((id: string) => {
    const el = document.querySelector(`[data-note-id="${id}"]`);
    if (el === null) return 'gone';
    const style = (el as HTMLElement).style;
    const text = el.querySelector('.sticky-text');
    return [
      el.getAttribute('data-note-id'),
      style.left,
      style.top,
      getComputedStyle(el).backgroundColor,
      text?.textContent ?? '',
    ].join('|');
  }, id);
}

/** How many notes this page draws. */
export function noteCountOf(page: Page): Promise<number> {
  return page.evaluate(() => document.querySelectorAll('[data-note-id]').length);
}

/** Whether this page has a note open for typing. */
export function editorOpen(page: Page): Promise<boolean> {
  return page.evaluate(() => document.querySelectorAll('textarea').length > 0);
}

/** The one state every page agrees on, or the first difference between them. */
export function differences(a: BoardState, b: BoardState): string {
  if (a.count !== b.count) return `${a.count} notes against ${b.count}`;
  for (let index = 0; index < a.notes.length; index++) {
    if (a.notes[index] !== b.notes[index]) return `note ${index}: ${a.notes[index]} against ${b.notes[index]}`;
  }
  return '';
}

/** Every page draws the same board, and that is what "live" has to end in. */
export async function expectSameBoard(people: Person[], label: string): Promise<void> {
  const [first, ...rest] = people;
  const from = Date.now();
  await expect
    .poll(
      async () => {
        const mine = await boardStateOf(first!.page);
        for (const other of rest) {
          const difference = differences(mine, await boardStateOf(other.page));
          if (difference !== '') return `${other.name}: ${difference}`;
        }
        return '';
      },
      { timeout: E2E_EVENTUAL_TIMEOUT_MS, intervals: [50, 100, 250] },
    )
    .toBe('');
  record(label, people.map((person) => person.name).join('/'), Date.now() - from);
}

// --- waiting and reporting ---------------------------------------------------

/** Every wait measured so far, in the order it was measured. */
const waits: { label: string; who: string; ms: number }[] = [];

/** The waits measured so far, oldest first. */
export function measurements(): { label: string; who: string; ms: number }[] {
  return [...waits];
}

/**
 * Wait for a functional outcome, and note how long it took. Nothing fails on
 * time: the budget is printed next to the measurement so a slow change is
 * visible in the log without a test failing because a laptop was busy.
 */
export async function expectEventually<T>(
  label: string,
  actual: () => Promise<T>,
  expected: T,
  who = 'board',
): Promise<void> {
  const from = Date.now();
  await expect
    .poll(actual, { timeout: E2E_EVENTUAL_TIMEOUT_MS, intervals: [50, 100, 250] })
    .toEqual(expected);
  record(label, who, Date.now() - from);
}

function record(label: string, who: string, ms: number): void {
  waits.push({ label, who, ms });
  const over = ms > LIVE_UPDATE_LATENCY_BUDGET_MS ? ` over the ${LIVE_UPDATE_LATENCY_BUDGET_MS}ms budget (not asserted)` : '';
  console.log(`  latency  ${label} [${who}] ${ms}ms${over}`);
}

/**
 * Wait for a board that was out of reach to be agreed with the room again. This
 * one is allowed to take longer than a change is: the outage lasts as long as the
 * product says it may (CATCH_UP_TEST_OUTAGE_MS) and the retry then lands.
 */
export async function expectBoardAgreedAgain(who: Person, label: string): Promise<void> {
  const from = Date.now();
  await expect
    .poll(() => connectionStateOf(who.page), {
      timeout: CATCH_UP_TEST_OUTAGE_MS + E2E_EVENTUAL_TIMEOUT_MS,
      intervals: [100, 250, 500],
    })
    .toBe('confirmed');
  // The board is reachable again, so from here on anything the socket complains
  // about is a problem and not the outage.
  who.expectingOutage = false;
  console.log(`  outage   ${label}: the board came back after ${Date.now() - from}ms`);
}

/** Percentiles of the waits so far, printed against the budget. */
export function reportLatency(title: string): void {
  const values = Array.from(waits.values()).map((value) => value.ms);
  if (values.length === 0) return;
  const sorted = [...values].sort((a, b) => a - b);
  const at = (fraction: number): number => sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * fraction))];
  console.log(
    `\n${title}\n  ${values.length} changes: p50 ${at(0.5)}ms, p95 ${at(0.95)}ms, max ${at(1)}ms` +
      ` (budget ${LIVE_UPDATE_LATENCY_BUDGET_MS}ms, reported and not asserted)`,
  );
  waits.length = 0;
}

/**
 * Everyone leaves the board. Closing a context takes the page down, which runs
 * the connection's own teardown; a suite that ends without a complaint from
 * anybody is also the check that nobody else's board was disturbed by anybody
 * leaving it.
 */
export async function leaveAll(people: Person[]): Promise<void> {
  for (const person of people) await person.context.close();
}

/** Nothing on any of these pages should ever have gone wrong. */
export function expectNoProblems(people: Person[]): void {
  const problems = people.flatMap((person) => person.problems);
  expect(problems).toEqual([]);
}

/**
 * This person loses the board, for `ms` milliseconds, and gets it back by
 * themselves afterwards: their socket is closed and their reconnection attempts
 * are refused for that long. The board on their screen stays where it is and
 * stays workable, which is what the story asks of a board that cannot be reached.
 *
 * Not `context.setOffline`, which leaves an open socket open in every browser
 * (see sync/emulateOutage.ts for the probe).
 */
export async function loseTheBoard(person: Person, ms: number): Promise<void> {
  person.expectingOutage = true;
  await person.page.evaluate((ms: number) => window.__vidi6?.emulateOutage(ms), ms);
}
