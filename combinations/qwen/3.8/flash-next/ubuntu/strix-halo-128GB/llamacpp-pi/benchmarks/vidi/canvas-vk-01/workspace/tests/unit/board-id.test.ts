import { describe, it, expect } from 'vitest';

import {
  BOARD_ID_BYTES,
  BOARD_ID_PATTERN,
  isValidBoardId,
  newBoardId,
} from '../../src/shared/board-id';

/**
 * TC-01, TC-02 — board id validation and generation (sync.worker_entry).
 */

/** A hand-written valid id (base64url alphabet, 22 chars). */
const VALID_ID = 'V1a2b3c4D5e6F7g8h9i0j-';

describe('isValidBoardId (TC-01)', () => {
  it('accepts a 22-char base64url id generated by newBoardId', () => {
    expect(isValidBoardId(newBoardId())).toBe(true);
  });

  it('accepts a hand-written 22-char base64url id', () => {
    expect(isValidBoardId(VALID_ID)).toBe(true);
  });

  it('rejects a 21-char id (boundary below)', () => {
    expect(isValidBoardId(VALID_ID.slice(0, 21))).toBe(false);
  });

  it('rejects a 23-char id (boundary above)', () => {
    expect(isValidBoardId(`${VALID_ID}x`)).toBe(false);
  });

  it("rejects '+' (not in the base64url alphabet)", () => {
    expect(isValidBoardId('V1a2b3c4D5e6F7g8h9i0+j')).toBe(false);
  });

  it("rejects '../x' (path traversal attempt)", () => {
    expect(isValidBoardId('../x')).toBe(false);
  });

  it('rejects the empty string', () => {
    expect(isValidBoardId('')).toBe(false);
  });
});

describe('newBoardId (TC-02)', () => {
  it('produces ids matching BOARD_ID_PATTERN, 10 000 times, without duplicates', () => {
    const seen = new Set<string>();
    for (let i = 0; i < 10_000; i += 1) {
      const id = newBoardId();
      expect(id).toMatch(BOARD_ID_PATTERN);
      expect(id).toHaveLength(22);
      seen.add(id);
    }
    expect(seen.size).toBe(10_000);
  });

  it('uses BOARD_ID_BYTES random bytes', () => {
    expect(BOARD_ID_BYTES).toBe(16);
  });
});
