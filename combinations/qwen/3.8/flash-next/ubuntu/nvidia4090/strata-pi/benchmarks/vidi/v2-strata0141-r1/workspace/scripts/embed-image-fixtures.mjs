/**
 * Writes `tests/fixtures/embeddedImages.ts`.
 *
 * Integration tests run inside workerd, where `node:fs` cannot reach the
 * repository - so the fixture bytes are embedded as base64 in a module the
 * Workers test runtime can import. The files themselves stay the single source
 * of truth: run `node scripts/make-image-fixtures.mjs` first, then this.
 *
 * Only fixtures under 300 KB are embedded. `photo-large.jpg`, the fixture that
 * is *large but still legal*, is used by the Node-side suites that can read it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inDir = path.join(root, 'tests', 'fixtures', 'images');
const outFile = path.join(root, 'tests', 'fixtures', 'embeddedImages.ts');
const MAX_EMBED_BYTES = 300 * 1024;

const names = fs
  .readdirSync(inDir)
  .filter((name) => fs.statSync(path.join(inDir, name)).size <= MAX_EMBED_BYTES)
  .sort();

const lines = [
  '/**',
  ' * Fixture bytes as base64, generated by `scripts/embed-image-fixtures.mjs`.',
  ' *',
  ' * `tests/fixtures/images/` holds the real files (unit, component and e2e tests',
  ' * read them from Node); this module holds the same bytes for the integration',
  ' * suite, which runs inside workerd and has no access to the repository.',
  ' */',
  '',
  'const FIXTURES: Record<string, string> = {',
];
for (const name of names) {
  const bytes = fs.readFileSync(path.join(inDir, name));
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(bytes.toString('base64'))},`);
}
lines.push('};', '');
lines.push(
  '/** The bytes of fixture `name`, exactly as `tests/fixtures/images/<name>` holds them. */',
  'export function embeddedImage(name: string): Uint8Array {',
  '  const encoded = FIXTURES[name];',
  '  if (encoded === undefined) {',
  '    throw new Error(',
  '      `no embedded fixture "${name}" (too large to embed, or regenerate with scripts/embed-image-fixtures.mjs)`,',
  '    );',
  '  }',
  '  const binary = atob(encoded);',
  '  const bytes = new Uint8Array(binary.length);',
  '  for (let index = 0; index < binary.length; index += 1) {',
  '    bytes[index] = binary.charCodeAt(index);',
  '  }',
  '  return bytes;',
  '}',
  '',
  '/** Which fixtures this module carries. */',
  'export const EMBEDDED_FIXTURE_NAMES = Object.keys(FIXTURES);',
  '',
);

fs.writeFileSync(outFile, lines.join('\n'));
console.log(`embedded ${names.length} fixtures into ${outFile}`);
