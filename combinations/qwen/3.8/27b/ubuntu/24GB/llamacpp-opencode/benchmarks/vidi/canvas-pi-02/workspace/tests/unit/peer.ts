import * as Y from 'yjs';
import {
  createSticky,
  getStickyText,
  initDoc,
  LOCAL_ORIGIN,
  resizeObjects,
  setStickyColor,
} from '../../src/shared/board-model';

/**
 * Simulated remote peer for the undo unit tests (story 8, task 6).
 *
 * A second real Y.Doc, kept in sync with the local doc:
 *  - local transactions marked LOCAL_ORIGIN are forwarded to the peer's doc
 *    (what a y-websocket room would relay);
 *  - `peer(fn)` runs fn on the peer's doc and applies the resulting updates
 *    to the local doc with PEER_ORIGIN — the origin a synced update carries
 *    on this client (never LOCAL_ORIGIN, so the undo controller must not
 *    capture it).
 *
 * Only LOCAL_ORIGIN updates are forwarded local -> peer: the peer replica
 * mirrors exactly what the room would hold, and updates applied to the local
 * doc from the peer (or from a board load) are not bounced back.
 */

/** Origin of changes generated by the simulated peer. */
export const PEER_ORIGIN = Symbol('vidi6.test.peer');

/** Origin of a simulated story 4 board load (the room's initial state). */
export const LOAD_ORIGIN = Symbol('vidi6.test.load');

export class TestPeer {
  readonly local: Y.Doc;
  private readonly remote: Y.Doc;

  constructor() {
    this.local = new Y.Doc();
    initDoc(this.local);
    this.remote = new Y.Doc();
    initDoc(this.remote);
    // y-websocket's sync protocol exchanges full state on join, so each
    // side holds the other's client baseline before any incremental update
    // flows. Replicate that: seed each doc with the other's current (meta-only)
    // state. Without this, Yjs rejects items whose clock outruns what the
    // target has seen from that client ("missing earlier structs").
    Y.applyUpdate(this.remote, Y.encodeStateAsUpdate(this.local), PEER_ORIGIN);
    Y.applyUpdate(this.local, Y.encodeStateAsUpdate(this.remote), PEER_ORIGIN);
    this.local.on('update', (update, origin) => {
      if (origin !== LOCAL_ORIGIN) return;
      Y.applyUpdate(this.remote, update, PEER_ORIGIN);
    });
  }

  /** Run fn on the peer's doc; the resulting updates land on the local doc as PEER_ORIGIN. */
  peer(fn: (doc: Y.Doc) => void): void {
    const updates: Uint8Array[] = [];
    const collect = (update: Uint8Array): void => {
      updates.push(update);
    };
    this.remote.on('update', collect);
    try {
      fn(this.remote);
    } finally {
      this.remote.off('update', collect);
    }
    for (const update of updates) {
      Y.applyUpdate(this.local, update, PEER_ORIGIN);
    }
  }
}

/**
 * Seed a doc with sticky notes (unit fixtures). Each note is created centred
 * at (x, y); text, colour and an explicit size are optional. Returns the ids.
 */
export function buildNotes(
  doc: Y.Doc,
  notes: Array<{ x: number; y: number; text?: string; color?: string; width?: number; height?: number }>,
): string[] {
  const ids: string[] = [];
  for (const n of notes) {
    const id = createSticky(doc, { x: n.x, y: n.y });
    ids.push(id);
    if (n.color !== undefined) setStickyColor(doc, id, n.color);
    if (n.text !== undefined) getStickyText(doc, id)!.insert(0, n.text);
    if (n.width !== undefined && n.height !== undefined) {
      resizeObjects(
        doc,
        new Map([[id, { x: n.x - n.width / 2, y: n.y - n.height / 2, width: n.width, height: n.height }]]),
      );
    }
  }
  return ids;
}
